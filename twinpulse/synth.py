def weight_for_age(age: int, sex: str) -> float:
    """Rough Indian growth reference (IAP 2015 median-ish), kg."""
    table = {7: 21, 8: 23.5, 9: 26, 10: 29, 11: 32, 12: 36, 13: 40, 14: 44, 15: 48, 16: 51}
    return table[age] * (0.97 if sex == "female" else 1.0)


def height_for_age(age: int, sex: str) -> float:
    table = {7: 120, 8: 126, 9: 131, 10: 137, 11: 142, 12: 148, 13: 154, 14: 159, 15: 162, 16: 165}
    return table[age] * (0.98 if sex == "female" else 1.0)


@njit(cache=True)
def _generate(si_t, sg, gb, cf, ex, ib, tau_l, bolus, inj, carbs, steps, awake, hypo_unaware, noise, cgm_noise):
    """Free-running patient with counter-regulation and self-treated lows while awake."""
    T = bolus.shape[0]
    G = 140.0
    X = 0.0
    S1 = 0.0
    S2 = 0.0
    L1 = ib * tau_l
    L2 = ib * tau_l
    Q1 = 0.0
    Q2 = 0.0
    E = 0.0
    last_rescue = -100
    g_true = np.empty(T)
    rescue = np.zeros(T)
    for t in range(T):
        si = si_t[t]
        S1 += bolus[t]
        L1 += inj[t]
        Q1 += carbs[t]
        if awake[t] == 1 and G < 68.0 and t - last_rescue > 6:
            Q1 += 15.0  # glucose biscuits / juice
            rescue[t] = 15.0
            last_rescue = t
        for _ in range(5):
            ia = S2 / TAU_I + L2 / tau_l
            dS1 = -S1 / TAU_I
            dS2 = (S1 - S2) / TAU_I
            dL1 = -L1 / tau_l
            dL2 = (L1 - L2) / tau_l
            dQ1 = -KABS * Q1
            dQ2 = KABS * (Q1 - Q2)
            ra = cf * KABS * Q2
            dX = -P2 * X + P2 * si * (ia - ib)
            a = steps[t] / STEP_NORM
            if a > 1.5:
                a = 1.5
            dE = (a - E) / TAU_E
            counter = 0.0
            if G < 70.0:
                counter = (0.02 if hypo_unaware == 0 else 0.008) * (70.0 - G)
            dG = -(sg + X) * G + sg * gb + ra - ex * E * G + counter
            S1 += dS1
            S2 += dS2
            L1 += dL1
            L2 += dL2
            Q1 += dQ1
            Q2 += dQ2
            X += dX
            E += dE
            G += dG
        G += noise[t]
        if G < 30.0:
            G = 30.0
        if G > 450.0:
            G = 450.0
        g_true[t] = G
    cgm = np.empty(T)
    e = 0.0
    for t in range(T):
        e = 0.8 * e + cgm_noise[t]
        c = g_true[t] + e
        cgm[t] = min(max(c, 40.0), 400.0)
    return g_true, cgm, rescue


def _slot(day: int, hhmm: str) -> int:
    h, m = int(hhmm[:2]), int(hhmm[3:])
    return day * 288 + (h * 60 + m) // 5


def generate_child(p: dict) -> tuple[pd.DataFrame, dict]:
    rng = np.random.default_rng(p["seed"])
    T = DAYS * 288 + 7 * 12 + 1  # through 07:00 after the last night
    bw = weight_for_age(p["age"], p["sex"])
    puberty = 1.15 if p["age"] >= 12 else 1.0
    tdd = round(bw * 0.85 * puberty * rng.uniform(0.9, 1.1), 1)
    si = si_from_tdd(tdd) * np.exp(rng.normal(0, 0.15))
    phys = dict(si=si, sg=0.004, gb=rng.uniform(GB_LO, GB_HI), cf=3.6 * np.exp(rng.normal(0, 0.1)),
                ex=rng.uniform(EX_LO, EX_HI), tdd=tdd, bw=bw)
    # Day-to-day insulin sensitivity varies (growth hormone, illness, stress): the reason nights differ.
    si_day = np.exp(rng.normal(0, SI_DAY_SD, DAYS + 1))

    bolus = np.zeros(T)
    inj = np.zeros(T)
    carbs = np.zeros(T)
    steps = np.zeros(T)
    awake = np.zeros(T, dtype=np.int64)
    icr = 500.0 / tdd
    play_days = []
    regimen = p["regimen"]
    tau_l = LONG_ACTING["nph"] if regimen in ("nph_regular", "premixed") else LONG_ACTING["glargine"]
    if regimen == "glargine_rapid":
        ib = tdd * 0.45 / 1440.0
    elif regimen == "nph_regular":
        ib = tdd * (2 / 3 * 2 / 3 + 1 / 3 * 1 / 2) / 1440.0
    else:
        ib = tdd * 0.7 / 1440.0

    for day in range(DAYS):
        school = (START + pd.Timedelta(days=day)).dayofweek < 6
        wake, sleep = _slot(day, "06:30"), _slot(day, "22:30")
        awake[wake:sleep] = 1
        steps[wake:sleep] = rng.poisson(45 if school else 30, sleep - wake)
        meals = {"07:30": rng.normal(50, 8), "11:00": rng.normal(15, 4) if school else 0,
                 "13:15": rng.normal(50, 10), "17:00": rng.normal(25, 6), "21:00": rng.normal(65, 12)}
        meal_t = {k: _slot(day, k) + int(rng.integers(-3, 4)) for k in meals}
        for k, g in meals.items():
            carbs[meal_t[k]] += max(g, 0)
        play = rng.random() < p["play_prob"]
        if play:
            play_days.append(day)
            s = _slot(day, "17:30") + int(rng.integers(-2, 3))
            steps[s:s + int(rng.integers(9, 15))] += rng.normal(480, 60, size=1).clip(250, 700)
        # Insulin
        if regimen == "nph_regular":
            m, e = tdd * 2 / 3, tdd * 1 / 3
            inj[meal_t["07:30"] - 3] += m * 2 / 3
            bolus[meal_t["07:30"] - 3] += m * 1 / 3
            inj[meal_t["21:00"] - 3] += e * 1 / 2
            bolus[meal_t["21:00"] - 3] += e * 1 / 2 * rng.uniform(0.85, 1.15)
        elif regimen == "premixed":
            for k, share in [("07:30", 0.6), ("21:00", 0.4)]:
                inj[meal_t[k] - 3] += tdd * share * 0.7
                bolus[meal_t[k] - 3] += tdd * share * 0.3
        else:
            inj[_slot(day, "21:45")] += tdd * 0.45
            for k in ["07:30", "13:15", "21:00"]:
                bolus[meal_t[k]] += round(meals[k] / icr * rng.uniform(0.85, 1.15) * 2) / 2
            if rng.random() < 0.5:
                bolus[meal_t["17:00"]] += round(meals["17:00"] / icr * 2) / 2
    # warm start: insulin already on board from the day before
    noise = rng.normal(0, 1.2, T)
    cgm_noise = rng.normal(0, 2.5, T)
    si_t = phys["si"] * np.repeat(si_day, 288)[:T]
    g_true, cgm, rescue = _generate(si_t, phys["sg"], phys["gb"], phys["cf"], phys["ex"], ib, tau_l, bolus,
                                    inj, carbs, steps, awake, int(p["hypo_unaware"]), noise, cgm_noise)
    times = pd.date_range(START, periods=T, freq="5min")
    hr = 92 - 0.6 * (p["age"] - 7) + steps / 12 + rng.normal(0, 3, T)
    hr = np.where(awake == 1, hr, hr - 14)
    if not p["hypo_unaware"]:
        hr = hr + np.where(g_true < 65, 12, 0)
    df = pd.DataFrame({"time": times, "glucose": cgm, "glucose_true": g_true, "carbs": carbs + rescue,
                       "bolus": bolus, "basal": 0.0, "basal_inj": inj, "steps": steps.round(), "hr": hr.round(1),
                       "awake": awake})
    if p["mode"] == "fingerstick":
        fs = np.full(T, np.nan)
        times_of_day = ["07:20", "21:00", "13:00"][: p["strips_per_day"]] if p["strips_per_day"] < 3 else \
            ["07:20", "13:00", "21:00"]
        for day in range(DAYS):
            for hm in times_of_day + ["22:15"]:
                i = _slot(day, hm)
                fs[i] = round(g_true[i] * rng.normal(1, 0.05))
        df["fingerstick"] = fs
    else:
        df["fingerstick"] = np.nan
    meta = {**p, **phys, "ib": ib, "tau_l": tau_l, "insulin_type": "nph" if tau_l == LONG_ACTING["nph"] else "glargine",
            "play_days": play_days, "regimen_label": REGIMEN_LABEL[regimen]}
    return df, meta


def fhir_bundle(meta: dict, df: pd.DataFrame) -> dict:
    """A small FHIR R4 bundle: Patient, Condition, Observations, MedicationStatements, Consent."""
    rng = np.random.default_rng(meta["seed"] + 100)
    pid = meta["id"]
    born = 2026 - meta["age"]
    dx_age = max(2, meta["age"] - int(rng.integers(1, 6)))
    g = df["glucose_true"]
    gmi = 3.31 + 0.02392 * g.mean()
    hba1c = round(gmi + (0.6 if rng.random() < 0.5 else 0.0), 1)  # iron-deficiency anaemia can push HbA1c up
    hb = round(rng.normal(10.8, 0.8), 1) if hba1c > gmi + 0.3 else round(rng.normal(12.4, 0.6), 1)
    hla = rng.choice(["HLA-DR3/DR4 (highest-risk)", "HLA-DR3/DR3", "HLA-DR4/DR4", "HLA-DR3/X"])
    abs_ = {"GAD65": bool(rng.random() < 0.8), "IA-2": bool(rng.random() < 0.6), "ZnT8": bool(rng.random() < 0.5)}
    severe_hypos = int(rng.integers(0, 3)) + (1 if meta["hypo_unaware"] else 0)

    def obs(code_system, code, display, value, unit=None, text=None):
        o = {"resourceType": "Observation", "id": f"{pid}-{code}", "status": "final",
             "code": {"coding": [{"system": code_system, "code": code, "display": display}], "text": display},
             "subject": {"reference": f"Patient/{pid}"}, "effectiveDateTime": "2026-10-01"}
        if unit:
            o["valueQuantity"] = {"value": value, "unit": unit}
        else:
            o["valueString"] = text if text is not None else str(value)
        return {"resource": o}

    loinc, snomed = "http://loinc.org", "http://snomed.info/sct"
    entries = [
        {"resource": {"resourceType": "Patient", "id": pid,
                      "identifier": [{"system": "urn:twinpulse:synthetic-abha", "value": f"91-{uuid.UUID(int=meta['seed']).hex[:4]}-SYNTH"}],
                      "name": [{"given": [meta["name"]], "text": f"{meta['name']} (synthetic)"}],
                      "gender": meta["sex"], "birthDate": f"{born}-06-15",
                      "address": [{"text": meta["town"], "country": "IN"}],
                      "communication": [{"language": {"text": meta["language"]}, "preferred": True}],
                      "contact": [{"relationship": [{"text": "Parent/guardian"}], "name": {"text": meta["parent"]}}]}},
        {"resource": {"resourceType": "Condition", "id": f"{pid}-t1d", "subject": {"reference": f"Patient/{pid}"},
                      "code": {"coding": [{"system": snomed, "code": "46635009", "display": "Type 1 diabetes mellitus"}]},
                      "onsetAge": {"value": dx_age, "unit": "a"}, "clinicalStatus": {"text": "active"}}},
        obs(loinc, "4548-4", "Hemoglobin A1c", hba1c, "%"),
        obs(loinc, "718-7", "Hemoglobin", hb, "g/dL"),
        obs(loinc, "29463-7", "Body weight", round(meta["bw"], 1), "kg"),
        obs(loinc, "8302-2", "Body height", height_for_age(meta["age"], meta["sex"]), "cm"),
        obs("urn:twinpulse", "tdd", "Total daily insulin dose", meta["tdd"], "U/day"),
        obs("urn:twinpulse", "severe-hypo-12m", "Severe hypoglycaemia episodes, last 12 months", severe_hypos, "episodes"),
        obs("urn:twinpulse", "hypo-awareness", "Hypoglycaemia awareness", None,
            text="Impaired (few warning signs)" if meta["hypo_unaware"] else "Normal"),
        obs("urn:twinpulse", "hla", "HLA risk genotype (synthetic)", None, text=str(hla)),
        obs("urn:twinpulse", "autoantibodies", "Islet autoantibodies (synthetic)", None,
            text=", ".join(f"{k} {'positive' if v else 'negative'}" for k, v in abs_.items())),
        obs("urn:twinpulse", "strips", "Glucose test strips affordable per day", meta["strips_per_day"], "strips/day"),
        {"resource": {"resourceType": "MedicationStatement", "id": f"{pid}-insulin", "status": "active",
                      "subject": {"reference": f"Patient/{pid}"},
                      "medicationCodeableConcept": {"text": meta["regimen_label"]},
                      "note": [{"text": f"Supply: {meta['insulin_source']}"}]}},
        {"resource": {"resourceType": "Consent", "id": f"{pid}-consent", "status": "active",
                      "scope": {"text": "Treatment"},
                      "category": [{"text": "Verifiable parental consent (DPDP Act 2023, s.9) for health services by the clinic"}],
                      "patient": {"reference": f"Patient/{pid}"},
                      "performer": [{"display": meta["parent"]}],
                      "provision": {"type": "permit", "purpose": [{"display": "Provision of health services to the child"}]}}},
    ]
    return {"resourceType": "Bundle", "type": "collection", "id": f"{pid}-bundle",
            "meta": {"tag": [{"code": "SYNTHETIC", "display": "Synthetic demo data - not a real person"}]},
            "entry": entries}, {"hba1c": hba1c, "hb": hb, "hla": str(hla), "autoantibodies": abs_,
                                "severe_hypos_12m": severe_hypos, "diagnosed_age": dx_age}


def build_demo():
    os.makedirs(DEMO, exist_ok=True)
    cohort = []
    for p in PERSONAS:
        df, meta = generate_child(p)
        bundle, ehr = fhir_bundle(meta, df)
        meta.update(ehr)
        df.to_parquet(os.path.join(DEMO, f"{p['id']}.parquet"), index=False)
        with open(os.path.join(DEMO, f"{p['id']}_fhir.json"), "w") as f:
            json.dump(bundle, f, indent=2)
        meta = {k: (float(v) if isinstance(v, (np.floating,)) else v) for k, v in meta.items()}
        cohort.append(meta)
        g = df["glucose_true"]
        night = df["time"].dt.hour < 6
        print(f"{p['id']} {p['name']:7s} {p['regimen']:15s} TDD {meta['tdd']:5.1f}  mean {g.mean():5.0f}  "
              f"TIR {((g >= 70) & (g <= 180)).mean():.0%}  TBR {(g < 70).mean():.1%}  night TBR {(g[night] < 70).mean():.1%}")
    with open(os.path.join(DEMO, "cohort.json"), "w") as f:
        json.dump(cohort, f, indent=2, default=str)


if __name__ == "__main__":
    build_demo()
